#!/usr/bin/env node
/**
 * Writes the nginx snippet that sets the security headers (sp7-plan.md, T10).
 *
 * The policy lives in one place — `packages/shared/src/security-headers.ts` —
 * and the static server that serves the built apps has to send exactly what
 * the dev server sent, or the browser suites prove nothing about production.
 * So the snippet is generated at image build time rather than hand-copied,
 * because a hand-copied content security policy is the one that goes stale.
 *
 * Usage: node scripts/render-nginx-headers.mjs <clinical|portal> <output path>
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Imported by path rather than by name: this script is run from the repository
// root, which does not itself depend on the shared package, so a bare specifier
// would not resolve. The path is relative to this file, so it works the same in
// a Docker build stage as it does on a laptop.
const HERE = path.dirname(fileURLToPath(import.meta.url));
const { securityHeaders } = await import(
  pathToFileURL(path.resolve(HERE, '..', 'packages', 'shared', 'dist', 'esm', 'index.js')).href
);

const [surface, output] = process.argv.slice(2);

if (surface !== 'clinical' && surface !== 'portal') {
  console.error('Usage: render-nginx-headers.mjs <clinical|portal> <output path>');
  process.exit(1);
}

if (!output) {
  console.error('An output path is required');
  process.exit(1);
}

const headers = securityHeaders(surface);

const lines = [
  `# Generated by scripts/render-nginx-headers.mjs for the ${surface} app.`,
  '# Do not edit: change packages/shared/src/security-headers.ts instead.',
  '',
  // `always` so that the headers are on an error page too — a 404 from the
  // static server is still a response a browser will act on.
  ...Object.entries(headers).map(
    ([header, value]) => `add_header ${header} "${value.replace(/"/g, '\\"')}" always;`,
  ),
  '',
];

mkdirSync(path.dirname(output), { recursive: true });
writeFileSync(output, lines.join('\n'), 'utf8');

console.log(`Wrote ${String(Object.keys(headers).length)} headers for ${surface} to ${output}`);
